#!/usr/bin/env bash
# Regenerates lib/extreme/messages/event_store.pb.ex from include/event_store.proto.
# Needs protoc and protoc-gen-elixir on PATH: mix escript.install hex protobuf <version in mix.lock>
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/lib/extreme/messages/event_store.pb.ex"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# protoc rejects enum values named like a sibling field (`error`), so rename them for protoc only.
sed -E 's/^([[:space:]]*)error = /\1enum_error = /' "$root/include/event_store.proto" > "$tmp/event_store.proto"

protoc --proto_path="$tmp" --elixir_out="$tmp" \
  --elixir_opt=package_prefix=extreme.messages "$tmp/event_store.proto"

{
  echo "# Generated by scripts/gen_messages.sh from include/event_store.proto. Do not edit."
  echo
  sed 's/field :enum_error, /field :error, /' "$tmp/extreme/messages/event_store.pb.ex" |
    awk '
      /use Protobuf/ { in_use = 1; is_enum = 0 }
      in_use && /enum: true/ { is_enum = 1 }
      { print }
      in_use && /syntax: :proto2/ {
        in_use = 0
        if (!is_enum) print "\n  use Extreme.Messages.Compat"
      }
    '
} > "$out"

cd "$root" && mix format
